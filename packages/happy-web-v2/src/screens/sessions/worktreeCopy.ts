export function worktreeCopy(lang: string): WorktreeCopy {
    return lang.startsWith('zh') ? zh : en;
}

/** Stable daemon error code → sentence (falls back to the raw message). */
export function worktreeErrorText(copy: WorktreeCopy, error: string): string {
    const code = error.split(':')[0].trim();
    return copy.errors[code] ?? error;
}
